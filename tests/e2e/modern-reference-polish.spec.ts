import { test, expect } from '@playwright/test'
for (const viewport of [{ width: 1366, height: 768 }, { width: 390, height: 844 }]) {
  test(`${viewport.width}px只读查询包含真实角色和资产摘要、图文帮助及可滚动全表`, async ({ page }) => {
    await page.setViewportSize(viewport)
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto('/tests/fixtures/modern-reference-polish.html')
    await page.screenshot({ path: `/tmp/reference-polish-assets-${viewport.width}.png` })
    await expect(page.getByTestId('reference-asset-summary').locator('article')).toHaveCount(4)
    await expect(page.getByTestId('reference-summary-player-1').getByRole('img', { name: '妮妮', exact: true })).toHaveAttribute('src', /champions\/12.png$/)
    await expect(page.getByTestId('asset-standings').locator('tbody tr')).toHaveCount(4)
    await page.getByTestId('reference-stocks').click()
    await expect(page.getByTestId('reference-stock-summary')).toContainText('45')
    await page.getByLabel('查询角色').selectOption('2')
    await expect(page.getByTestId('reference-stock-summary')).toContainText('70')
    await expect(page.getByTestId('stock-overview').locator('tbody tr')).toHaveCount(12)
    await page.screenshot({ path: `/tmp/reference-polish-stocks-${viewport.width}.png` })
    await page.getByTestId('reference-holdings').click()
    await expect(page.getByTestId('reference-holdings-summary').locator('article')).toHaveCount(4)
    await expect(page.getByTestId('holdings-overview').locator('tbody tr')).toHaveCount(15)
    const scroll = page.locator('.table-scroll')
    if (viewport.width === 390) expect(await scroll.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
    await page.screenshot({ path: `/tmp/reference-polish-holdings-${viewport.width}.png` })
    await page.getByTestId('reference-help').click()
    await expect(page.getByTestId('help-card')).toHaveCount(17)
    await expect(page.locator('.help-card-art')).toHaveCount(17)
    await expect.poll(() => page.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
    await page.screenshot({ path: `/tmp/reference-polish-help-${viewport.width}.png` })
    await page.locator('.card-heading').scrollIntoViewIfNeeded()
    await page.screenshot({ path: `/tmp/reference-polish-cards-${viewport.width}.png` })
    const panel = (await page.getByRole('dialog').boundingBox())!
    expect(panel.width).toBeLessThanOrEqual(viewport.width)
    await page.keyboard.press('Escape'); await expect(page.getByTestId('closed')).toHaveText('true')
    expect(errors).toEqual([])
  })
  test(`${viewport.width}px地图信息可视化展示建筑等级并保留真实收费`, async ({ page }) => {
    await page.setViewportSize(viewport)
    await page.goto('/tests/fixtures/modern-reference-polish.html?tab=map')
    await page.screenshot({ path: `/tmp/reference-polish-map-${viewport.width}.png` })
    await expect(page.getByTestId('map-property-level')).toHaveAttribute('aria-label', '建筑等级 3 / 5')
    await expect(page.getByTestId('map-info')).toContainText('4500')
    const box = (await page.getByTestId('map-info').boundingBox())!
    expect(box.x).toBeGreaterThanOrEqual(0); expect(box.x + box.width).toBeLessThanOrEqual(viewport.width)
    await page.getByRole('button', { name: '关闭地图信息' }).click()
    await expect(page.getByTestId('closed')).toHaveText('true')
  })
}
