import { expect, test } from '@playwright/test'

const fixture = '/tests/fixtures/modern-save-polish.html'
for (const viewport of [{name:'desktop',width:1366,height:768},{name:'mobile',width:390,height:844},{name:'short',width:1024,height:500}]) {
  test(`存档卡布局与确认操作 ${viewport.name}`, async ({ page }) => {
    await page.setViewportSize(viewport)
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.goto(fixture)
    await expect(page).toHaveTitle('手动存读档 · 受控界面夹具')
    const panel = page.getByRole('dialog', {name:'手动存读档',exact:true})
    await expect(panel).toBeVisible()
    await expect(page.locator('vite-error-overlay')).toHaveCount(0)
    await expect(page.getByTestId('save-row-1')).toContainText('第17轮')
    await expect(page.getByTestId('save-row-1').getByRole('list', {name:'对局玩家'})).toContainText('自定义玩家')
    await expect(page.getByTestId('load-slot-2')).toBeDisabled()
    const bounds = await panel.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.y).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(viewport.width)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(viewport.height)
    expect(await panel.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await expect(page.getByRole('button',{name:'关闭，返回对局'})).toBeInViewport()
    await page.screenshot({path:`/tmp/save-polish/${viewport.name}.png`})
    await page.getByTestId('save-slot-1').click()
    await expect(page.getByRole('alertdialog')).toContainText('槽位 1 · 覆盖存档')
    await page.getByRole('button',{name:'取消',exact:true}).click()
    await expect(page.getByRole('alertdialog')).toHaveCount(0)
    await page.getByTestId('load-slot-1').click()
    await expect(page.getByTestId('load-confirm')).toBeInViewport()
    await page.screenshot({path:`/tmp/save-polish/${viewport.name}-confirm.png`})
    await page.getByTestId('load-confirm').click()
    expect(await page.evaluate(() => (window as unknown as {fixtureEvents:unknown[]}).fixtureEvents)).toEqual([{kind:'load',slot:1}])
    await page.getByTestId('save-slot-2').click()
    expect(await page.evaluate(() => (window as unknown as {fixtureEvents:unknown[]}).fixtureEvents)).toEqual([{kind:'load',slot:1},{kind:'save',slot:2}])
    expect(errors).toEqual([])
  })
}

test('错误与忙碌状态清晰分开', async ({page}) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto(`${fixture}?state=error`)
  await expect(page.getByRole('alert')).toContainText('当前对局保留')
  await page.getByRole('button',{name:'重试同一保存请求'}).click()
  expect(await page.evaluate(() => (window as unknown as {fixtureEvents:unknown[]}).fixtureEvents)).toEqual([{kind:'retry'}])
  await page.screenshot({path:'/tmp/save-polish/mobile-error.png'})
  await page.goto(`${fixture}?state=busy`)
  await expect(page.getByRole('status')).toHaveText('正在处理，请稍候…')
  await expect(page.getByTestId('save-slot-1')).toBeDisabled()
  await expect(page.getByTestId('load-slot-1')).toBeDisabled()
  await expect(page.getByRole('button',{name:'关闭，返回对局'})).toBeEnabled()
  await page.screenshot({path:'/tmp/save-polish/mobile-busy.png'})
})
